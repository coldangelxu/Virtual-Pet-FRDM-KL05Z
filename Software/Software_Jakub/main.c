void I2C_OLED_INIT(void) {            //i2c for oled initialization
    SIM->SCGC4 |= SIM_SCGC4_I2C0_MASK;
    SIM->SCGC5 |= SIM_SCGC5_PORTB_MASK;
    PORTB->PCR[3] = PORT_PCR_MUX(2);
    PORTB->PCR[4] = PORT_PCR_MUX(2);
    I2C0->C1 &= ~(I2C_C1_IICEN_MASK);
    I2C0->F = 0x11; //(00 010001);
    I2C0->C1 |= I2C_C1_IICEN_MASK;
}
void OLED_WRITE_1BYTE(uint8_t byte){         //Sending 1 byte to OLED
    i2c_enable();
    i2c_tran();
    i2c_m_start();
    i2c_send(OLED_ADDR);
    i2c_wait();
    i2c_send(0x00);
    i2c_wait();
    i2c_send(byte);
    i2c_wait();
    i2c_m_stop();
    i2c_disable();
}
void OLED_INIT(void) {              //Oled configuratiion
        I2C_OLED_INIT();

        OLED_WRITE_1BYTE(0xAE); // Display OFF
    OLED_WRITE_1BYTE(0xA8); // Initialize number of rows
    OLED_WRITE_1BYTE(0x3F); // Set number of rows
    OLED_WRITE_1BYTE(0xAD); // DC-DC Control Mode Set
    OLED_WRITE_1BYTE(0x8B); // Pump on
    OLED_WRITE_1BYTE(0xA1); // Segment remap ( to get good orientation )
    OLED_WRITE_1BYTE(0xC8); // COM Output Scan Direction
    OLED_WRITE_1BYTE(0x81); // Set Contrast
    OLED_WRITE_1BYTE(0xBF); // Contrast level (0x00 to 0xFF)
    OLED_WRITE_1BYTE(0xAF); // Display ON
                            // Full list of command in datasheet SH1106
}
void OLED_DISPLAY_CLEAR(void){                    // Clear OLED
    for(uint8_t y = 0; y < 8; y++){
        OLED_WRITE_1BYTE( 0xB0+y ); // Page adrress 0-7

        uint8_t column = 2;

        OLED_WRITE_1BYTE(0x00 | (column & 0x0F)); // Mask on 4 bits (LSB)
        OLED_WRITE_1BYTE(0x10 | ((column>>4)) & 0x0F); // Mask on 4 bits (MSB)
        i2c_enable();
        i2c_tran();
        i2c_m_start();
        i2c_send(OLED_ADDR);
        i2c_wait();
        i2c_send(0x40);
        i2c_wait();
        for(uint8_t c = 0;c < 128; c++){
            i2c_send(0x00);
            i2c_wait();
        }
        i2c_m_stop();
        i2c_disable();
    }
}
void OLED_DISPLAY_32x32(uint8_t x,uint8_t y_page, const uint8_t *bitmap ){               // Drawing bitmaps 32x32
    for(uint8_t y = 0; y < 4; y++){                                                      // 4 pages because 32bitsONbitmap / 8bitsPERpage = 4 pages
        OLED_WRITE_1BYTE( 0xB0+y+y_page );                                               // Page adrress

        uint8_t column = x + 2;

        OLED_WRITE_1BYTE(0x00 | (column & 0x0F)); // Mask on 4 bits (LSB)
        OLED_WRITE_1BYTE(0x10 | ((column>>4)) & 0x0F); // Mask on 4 bits (MSB)
        i2c_enable();
        i2c_tran();
        i2c_m_start();
        i2c_send(OLED_ADDR);
        i2c_wait();
        i2c_send(0x40);
        i2c_wait();
        for(uint8_t c = 0;c < 32; c++){
            i2c_send(bitmap[y*32+c]);
            i2c_wait();
        }
        i2c_m_stop();
        i2c_disable();
    }
}
